/* Synthetic history, real ordinary Chromium and real candidate HTTP server. */
'use strict';
const fs=require('fs'),path=require('path');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const output=process.argv[2],access=JSON.parse(fs.readFileSync(path.join(output,'access.json')));
let checks=0;
function check(value,message){if(!value)throw new Error(message);checks++;}
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM,args:['--no-sandbox']});
 try{
  let page=await browser.newPage({viewport:{width:1440,height:1000}});
  await page.goto(access.url+'/#token='+access.token);await page.waitForSelector('#studio[data-ready="true"]');
  check((await page.locator('#trust').innerText()).includes('Development'),'Candidate must not claim Stable');
  check(await page.locator('#canvas-run').isDisabled(),'Development session host must not execute Controller');
  await page.locator('.workspace-menu').evaluate(e=>e.open=true);
  await page.locator('#workspace-path').fill(access.source);await page.locator('#open-workspace').click();
  await page.waitForFunction(()=>document.querySelectorAll('.session-card').length===2);
  await page.locator('[data-go="sessions"]').first().click();
  const claude=page.locator('.session-card').filter({hasText:'claude ·'});
  await claude.getByRole('button',{name:'查看历史',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#session-messages').textContent.includes('VISIBLE answer'));
  const history=await page.locator('#session-messages').innerText();
  check(!/HIDDEN_REASONING|PRIVATE_COMMAND|PRIVATE_TOOL_RESULT|sk-fixture-/.test(history),'History exposed private blocks or credentials');
  check(await page.locator('#session-continue').isDisabled(),'External history must remain read only');
  await page.locator('#session-query').fill('hello');await page.locator('#session-search').click();
  await page.waitForFunction(()=>document.querySelector('#session-messages').textContent.includes('VISIBLE hello')&&!document.querySelector('#session-messages').textContent.includes('VISIBLE answer'));
  check((await page.locator('#session-messages').innerText()).includes('VISIBLE hello'),'Search must retain matching user message');
  check(await claude.getByRole('button',{name:'删除原始会话（不支持）',exact:true}).isDisabled(),'Native deletion must be disabled');
  await claude.getByRole('button',{name:'在 DevFlower 隐藏',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.session-card').length===1);
  await page.locator('#session-hidden').check();await page.waitForFunction(()=>document.querySelectorAll('.session-card').length===2);
  await page.getByRole('button',{name:'取消隐藏',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#sessions').textContent.includes('DevFlower 已隐藏'));
  await page.locator('#session-new').click();await page.locator('#session-profile').selectOption('default-codex');
  await page.locator('#session-prompt').fill('Synthetic UI preview only; do not spawn a model.');
  await page.locator('#session-prepare').click();await page.waitForSelector('#session-preview input');
  check((await page.locator('#session-preview').innerText()).includes('cwd '+access.source),'Preview must disclose effective cwd');
  check((await page.locator('#session-preview').innerText()).includes('read'),'Preview must disclose permission');
  await page.locator('#session-permission').selectOption('workspace-write');
  check(await page.locator('#session-preview').innerText()==='','Changing permission must discard prior confirmation');
  await page.locator('#session-permission').selectOption('read');
  await page.locator('#session-prepare').click();await page.waitForSelector('#session-preview input');
  await claude.getByRole('button',{name:'查看历史',exact:true}).click();
  check(await page.locator('#session-preview input').count()===0,'Selecting a different conversation must discard the old send permit');
  check(await page.locator('#session-compose').isHidden(),'Composer must not retain a different conversation target');
  await page.locator('#session-new').click();
  let releasePreview,previewDelivered;
  const previewBarrier=new Promise(resolve=>releasePreview=resolve),previewDone=new Promise(resolve=>previewDelivered=resolve);
  await page.route('**/api/session/prepare',async route=>{const response=await route.fetch();await previewBarrier;await route.fulfill({response});previewDelivered();});
  const delayedPreview=page.waitForRequest(r=>r.url().endsWith('/api/session/prepare'));
  const originalPrompt=await page.locator('#session-prompt').inputValue();
  await page.locator('#session-prepare').click();await delayedPreview;
  await page.locator('#session-prompt').fill('changed then reverted');await page.locator('#session-prompt').fill(originalPrompt);
  releasePreview();await previewDone;await page.unroute('**/api/session/prepare');await page.waitForTimeout(200);
  check(await page.locator('#session-preview input').count()===0,'An obsolete preview must not reappear after edit/revert');
  await page.screenshot({path:path.join(output,'synthetic-session-center.png')});
  const stale=page.waitForRequest(r=>r.url().includes('/api/session/history?'));
  let release,finished;const barrier=new Promise(resolve=>release=resolve),delivered=new Promise(resolve=>finished=resolve);
  await page.route('**/api/session/history?**',async route=>{const response=await route.fetch();await barrier;await route.fulfill({response});finished();});
  await claude.getByRole('button',{name:'查看历史',exact:true}).click();await stale;
  await page.locator('.workspace-menu').evaluate(e=>e.open=true);
  await page.locator('#workspace-path').fill(access.other);await page.locator('#open-workspace').click();
  await page.waitForFunction(p=>document.querySelector('#workspace-info').textContent.includes(p),access.other);
  release();await delivered;await page.unroute('**/api/session/history?**');
  await page.waitForTimeout(300);
  check(!(await page.locator('#session-messages').innerText()).includes('VISIBLE'),'Late history response leaked across workspace switch');
  check((await page.locator('#workspace-info').innerText()).includes('只读'),'Nonrepository workspace must open read only');
  check(await page.locator('#session-new').isDisabled(),'Read-only folder cannot run native sessions');
  // Subsequent persistence/reopen checks target source, not the unrelated
  // read-only workspace just used for the late-history isolation check.
  await page.locator('.workspace-menu').evaluate(e=>e.open=true);
  await page.locator('#recent').selectOption({label:access.source});
  await page.waitForFunction(p=>document.querySelector('#workspace-info').textContent.includes(p),access.source);
  await page.waitForFunction(()=>document.querySelectorAll('.session-card').length===2);
  await page.keyboard.press('Escape');
  await page.locator('#template-library summary').click();await page.locator('#template').selectOption('A');await page.locator('#new-draft').click();
  await page.waitForSelector('#canvas [data-node="developer"]');
  await page.locator('#workflow-name').fill('Issue9 swapped providers');
  await page.locator('#canvas [data-node="developer"] .node-body').dblclick();
  await page.locator('[data-field="provider"]').selectOption('claude');
  check(await page.locator('[data-field="profile"]').inputValue()==='default-claude','Developer Provider must bind a matching approved profile');
  await page.locator('[data-field="responsibility"]').fill('Implement the approved task');
  await page.keyboard.press('Escape');await page.locator('#canvas [data-node="reviewer"] .node-body').dblclick();
  await page.locator('[data-field="provider"]').selectOption('codex');
  check(await page.locator('[data-field="profile"]').inputValue()==='default-codex','Reviewer Provider must bind its actual adapter profile');
  await page.locator('.agent-advanced summary').click();
  check(await page.locator('[data-field="subagents"]').isDisabled(),'Unsupported subagents must remain disabled');
  await page.keyboard.press('Escape');await page.locator('#flow-options').click();
  const compileResponse=page.waitForResponse(r=>r.url().endsWith('/api/compile'));await page.locator('#compile').click();
  const compiled=await compileResponse;check(compiled.status()===200,'Canvas Provider swap must compile through real HTTP');
  const plan=await compiled.json();
  check(plan.runtime_gates.includes('freeze')&&plan.runtime_gates.includes('independent-review'),'Provider changes cannot remove trusted gates');
  check(plan.document.nodes.find(n=>n.type==='developer').config.provider==='claude'&&plan.document.nodes.find(n=>n.type==='reviewer').config.provider==='codex','Actual saved node providers must match UI choices');
  await page.keyboard.press('Escape');const saved=page.waitForResponse(r=>r.url().endsWith('/api/draft'));await page.locator('#save').click();const savedResponse=await saved;
  check(savedResponse.status()===200,'Edited workflow save must succeed');const savedDraft=await savedResponse.json();
  const status=await page.request.get(access.url+'/api/status?workspace='+encodeURIComponent(savedDraft.workspace),{headers:{Authorization:'Bearer '+access.token}});
  check(status.status()===200,'Saved workspace status must be available');const data=await status.json();
  check(data.workspaces.some(w=>w.id===savedDraft.workspace&&w.path===access.source),'Draft must belong to the source workspace');
  check(data.drafts.some(d=>d.id===savedDraft.id&&d.document.name==='Issue9 swapped providers'),'Saved draft must exist in its own workspace');
  await page.screenshot({path:path.join(output,'synthetic-provider-canvas.png')});
  await page.close();page=await browser.newPage();await page.goto(access.url+'/#token='+access.token);
  await page.waitForSelector('#studio[data-ready="true"]');
  await page.locator('.workspace-menu').evaluate(e=>e.open=true);
  check((await page.locator('#recent').innerText()).includes(access.source),'Recent workspaces must persist after browser close');
  await page.locator('#recent').selectOption({label:access.source});
  await page.waitForFunction(()=>document.querySelectorAll('.session-card').length===2);
  await page.waitForFunction(id=>Array.from(document.querySelector('#drafts').options).some(o=>o.value===id),savedDraft.id);
  check((await page.locator('#drafts').textContent()).includes('Issue9 swapped providers'),'Edited workflow must persist independently of browser session');
  await page.locator('[data-go="sessions"]').first().click();
  check(!(await page.locator('#sessions').innerText()).includes('DevFlower 已隐藏'),'Unhide must persist after browser close');
  await page.screenshot({path:path.join(output,'synthetic-session-center-reopened.png')});
  await page.locator('#panel-sessions summary').filter({hasText:'登记只读存储目录'}).click();
  await page.locator('#session-register-provider').selectOption('claude');
  for(let i=0;i<access.registered_roots.length;i++){
   await page.locator('#session-register-root').fill(access.registered_roots[i]);
   await page.locator('#session-register').click();
   await page.waitForFunction(n=>document.querySelectorAll('.session-card').length===n,3+i);
  }
  const registeredCards=access.registered_roots.map(root=>page.locator('.session-card').filter({hasText:root}));
  const handles=await Promise.all(registeredCards.map(card=>card.getAttribute('data-handle')));
  check(handles[0]!==handles[1],'Same UUID in two registered storage profiles must have distinct opaque handles');
  for(let i=0;i<registeredCards.length;i++){
   await registeredCards[i].getByRole('button',{name:'查看历史',exact:true}).click();
   await page.locator('#session-query').fill(access.registered_markers[i]);await page.locator('#session-search').click();
   await page.waitForFunction(marker=>document.querySelector('#session-messages').textContent.includes(marker),access.registered_markers[i]);
   check(!(await page.locator('#session-messages').innerText()).includes(access.registered_markers[1-i]),'Profile history must not alias another root');
   check(await page.locator('#session-continue').isDisabled(),'Read-only storage registration must not grant native execution');
  }
  await registeredCards[0].getByRole('button',{name:'在 DevFlower 隐藏',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.session-card').length===3);
  check(await registeredCards[1].count()===1,'Hiding one registered profile must preserve the other profile');
  await page.locator('#session-hidden').check();
  await page.waitForFunction(()=>document.querySelectorAll('.session-card').length===4);
  check(!(await registeredCards[1].innerText()).includes('DevFlower 已隐藏'),'Visibility metadata must remain independent per profile');
  await registeredCards[0].getByRole('button',{name:'取消隐藏',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#sessions').textContent.includes('DevFlower 已隐藏'));
  await page.reload();await page.waitForSelector('#studio[data-ready="true"]');
  await page.waitForFunction(()=>document.querySelectorAll('.session-card').length===4);
  await page.locator('[data-go="sessions"]').first().click();
  check(await registeredCards[0].getAttribute('data-handle')===handles[0]&&await registeredCards[1].getAttribute('data-handle')===handles[1],'Registered profile identities must persist after reload');
  await page.screenshot({path:path.join(output,'synthetic-registered-profiles.png')});
  const results={checks,passed:true,evidence_type:'ordinary Chromium/HTTP synthetic-history regression; not native/final acceptance'};
  fs.writeFileSync(path.join(output,'results.json'),JSON.stringify(results,null,2));console.log(JSON.stringify(results));
 }finally{await browser.close();}
})().catch(e=>{console.error(e.stack);process.exitCode=1;});
